"""Generate ``src/search_tables.rs`` from this interpreter's Unicode database.

The native search primitives must agree with ``str.casefold``, ``str.isdigit``
and ``str.isspace`` code point for code point, so the tables are dumped from
the interpreter rather than taken from a Rust crate with its own Unicode
version. Run with the CPython minor the module is built for::

    python native/kc_native/gen_search_tables.py > native/kc_native/src/search_tables.rs

``test/test_native_search_fallback.py`` regenerates the text in memory and
compares it with the committed file, so a stale table fails a test instead of
shipping.
"""

from __future__ import annotations

import sys
import unicodedata

_PER_LINE = 6


def _code_points() -> list[int]:
    return [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def _ranges(cps: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for c in cps:
        if out and out[-1][1] == c - 1:
            out[-1] = (out[-1][0], c)
        else:
            out.append((c, c))
    return out


def _rows(items: list[str], per: int = _PER_LINE) -> list[str]:
    return ["    " + " ".join(items[i : i + per]) for i in range(0, len(items), per)]


def render() -> str:
    cps = _code_points()
    digits = _ranges([c for c in cps if chr(c).isdigit()])
    spaces = [c for c in cps if chr(c).isspace()]
    folds: list[tuple[int, list[int]]] = []
    for c in cps:
        folded = chr(c).casefold()
        if folded != chr(c):
            folds.append((c, [ord(ch) for ch in folded]))
    if max(len(f) for _, f in folds) > 3:
        raise SystemExit("a casefold expansion is longer than 3 code points")

    lines = [
        "// @generated by native/kc_native/gen_search_tables.py -- do not edit by hand.",
        "",
        "/// `unicodedata.unidata_version` of the interpreter these tables came from.",
        f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// Inclusive code point ranges where `str.isdigit()` is true.",
        "pub const DIGIT_RANGES: &[(u32, u32)] = &[",
        *_rows([f"(0x{a:X}, 0x{b:X})," for a, b in digits]),
        "];",
        "",
        "/// Code points where `str.isspace()` is true, ascending.",
        "pub const SPACES: &[u32] = &[",
        *_rows([f"0x{c:X}," for c in spaces]),
        "];",
        "",
        "/// `(code point, folded code points, folded length)` for every code point",
        "/// whose `str.casefold()` differs from itself, ascending.",
        "pub const FOLDS: &[(u32, [u32; 3], u8)] = &[",
    ]
    rows = []
    for c, f in folds:
        padded = f + [0] * (3 - len(f))
        rows.append(f"(0x{c:X}, [0x{padded[0]:X}, 0x{padded[1]:X}, 0x{padded[2]:X}], {len(f)}),")
    lines += _rows(rows, 3)
    lines += ["];", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    sys.stdout.write(render())
